import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");
const args = process.argv.slice(2);
if (args.some((argument) => argument !== "--check" && !argument.startsWith("--output="))) {
  throw new Error("Usage: node tools/build-packaged-stdlib.mjs [--output=directory] [--check]");
}
const output = path.resolve(args.find((argument) => argument.startsWith("--output="))?.slice(9)
  ?? path.join(root, "build/shared-compiler"));
const registry = (await readFile(path.join(root, "compiler/native/vkf_stdlib_registry.hpp"), "utf8"))
  .replaceAll("\r", "");
const table = /std::array<ModuleDescriptor,\s*(\d+)> modules\{\{([\s\S]*?)\}\};/u.exec(registry);
if (!table) throw new Error("Native stdlib registry table was not found");
const entries = [...table[2].matchAll(/\{"([^"]+)",\s*"([^"]+)",\s*ImplementationClass::(\w+),\s*(true|false)\}/gu)]
  .map(([, module, source, implementation, native]) => ({ module, source, implementation, native: native === "true" }));
if (entries.length !== Number(table[1]) || new Set(entries.map(({ module }) => module)).size !== entries.length) {
  throw new Error("Native stdlib registry entries could not be read exactly");
}
entries.sort((left, right) => left.module < right.module ? -1 : left.module > right.module ? 1 : 0);
const modules = [], absent = [];
for (const entry of entries) {
  if (!/^[a-zA-Z0-9_/]+\.vkf$/u.test(entry.source) || entry.source.includes("..")) {
    throw new Error(`Invalid registered stdlib source path: ${entry.source}`);
  }
  let bytes;
  try { bytes = await readFile(path.join(root, "compiler/self_hosted/stdlib", entry.source)); }
  catch (error) {
    if (error.code !== "ENOENT" || (entry.native && entry.implementation !== "Intrinsic")) throw error;
    absent.push({ module: entry.module, source: entry.source });
    continue;
  }
  // The native driver removes CR before lexing. Canonicalize identically so
  // checkout line endings cannot alter the compiler's embedded source graph.
  const source = new TextDecoder("utf-8", { fatal: true }).decode(bytes).replaceAll("\r", "");
  if (source.includes("\0")) throw new Error(`NUL in stdlib source: ${entry.source}`);
  const hash = sha256(source);
  let delimiter = `VKF${hash.slice(0, 12)}`;
  for (let index = 0; source.includes(`)${delimiter}"`); index++) delimiter = `VKF${index.toString(16)}`;
  if (delimiter.length > 16) throw new Error(`Cannot delimit stdlib source: ${entry.source}`);
  modules.push({ ...entry, text: source, sha256: hash, bytes: Buffer.byteLength(source), delimiter });
}

const header = `// Generated by tools/build-packaged-stdlib.mjs; do not edit.
#pragma once
#include <array>
#include <string_view>
namespace vkf::module_linker::packaged {
struct SourceRecord {
    std::string_view module;
    std::string_view path;
    std::string_view source;
    std::string_view sha256;
};
inline constexpr std::array<SourceRecord, ${modules.length}> sources{{
${modules.map((entry) => `    {${JSON.stringify(entry.module)}, ${JSON.stringify(entry.source)}, std::string_view{R"${entry.delimiter}(${entry.text})${entry.delimiter}", ${entry.bytes}}, ${JSON.stringify(entry.sha256)}}`).join(",\n")}
}};
} // namespace vkf::module_linker::packaged
`;
const manifest = `${JSON.stringify({
  version: 1,
  normalization: "UTF-8; remove CR exactly as native normalize_source_for_lexer",
  registrySha256: sha256(registry),
  headerSha256: sha256(header),
  modules: modules.map(({ module, source, sha256, bytes }) => ({ module, source, sha256, bytes })),
  absent,
}, null, 2)}\n`;
const outputs = [["vkf_packaged_stdlib.generated.hpp", header], ["vkf_packaged_stdlib.manifest.json", manifest]];
if (!args.includes("--check")) await mkdir(output, { recursive: true });
for (const [name, content] of outputs) {
  const target = path.join(output, name);
  if (args.includes("--check")) {
    if (await readFile(target, "utf8") !== content) throw new Error(`Stale packaged stdlib: ${target}`);
  } else {
    let current;
    try { current = await readFile(target, "utf8"); }
    catch (error) { if (error.code !== "ENOENT") throw error; }
    if (current !== content) await writeFile(target, content);
  }
}
console.log(`Packaged ${modules.length} canonical stdlib modules; header SHA256 ${sha256(header)}`);

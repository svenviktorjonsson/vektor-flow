import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const catalogPath = path.join(repositoryRoot, "spec", "html-component-identities.json");
const browserPath = path.join(repositoryRoot, "web", "vf-ui", "vf-html-components.js");
const compilerPath = path.join(
  repositoryRoot,
  "compiler",
  "native",
  "vkf_html_component_catalog.generated.hpp",
);

function validateCatalog(value) {
  if (!Array.isArray(value) || value.length === 0) {
    throw new Error("HTML component identity catalog must be a non-empty array");
  }
  const identities = new Set();
  const tags = new Set();
  for (const entry of value) {
    if (!Array.isArray(entry) || entry.length !== 2) {
      throw new Error("HTML component identity catalog entries must be [identity, tag]");
    }
    const [identity, tag] = entry;
    if (!/^[A-Z][A-Za-z0-9]*$/.test(identity) || !/^[a-z][a-z0-9]*$/.test(tag)) {
      throw new Error(`invalid HTML component identity catalog entry ${JSON.stringify(entry)}`);
    }
    if (identity === "Script" || tag === "script") {
      throw new Error("Script must remain excluded from the HTML component identity catalog");
    }
    if (identities.has(identity) || tags.has(tag)) {
      throw new Error(`duplicate HTML component identity catalog entry ${JSON.stringify(entry)}`);
    }
    identities.add(identity);
    tags.add(tag);
  }
  return value;
}
function generateBrowser(catalog) {
  const encodedCatalog = JSON.stringify(catalog);
  return `// Generated by tools/generate-html-component-catalog.mjs. Do not edit by hand.
(function (global) {
  "use strict";

  const catalog = global.Object.freeze(${encodedCatalog}.map(function(entry) {
    return global.Object.freeze({ identity: entry[0], tag: entry[1] });
  }));
  const components = {};
  for (const entry of catalog) {
    const Component = class {
      constructor() {
        return global.document.createElement(entry.tag);
      }
    };
    global.Object.defineProperty(Component, "name", { value: entry.identity });
    components[entry.identity] = Component;
  }

  const internalTrees = new global.WeakMap();

  function adoptInternalTree(ownerRoot, elements) {
    if (!(ownerRoot instanceof global.Element) || !Array.isArray(elements)) {
      throw new TypeError("internal HTML component tree adoption requires an owner and elements");
    }
    const retained = elements.slice();
    for (const element of retained) {
      if (!(element instanceof global.Element) || !ownerRoot.contains(element)) {
        throw new TypeError("internal HTML component tree adoption received a detached element");
      }
    }
    internalTrees.set(ownerRoot, retained);
    return retained;
  }

  function applyInternalPatch(ownerRoot, record) {
    if (!(ownerRoot instanceof global.Element) || !record || record.version !== 1 ||
        !Number.isInteger(record.target) || record.target < 0 || !record.mutation) {
      throw new TypeError("private retained HTML patch is malformed");
    }
    const retained = internalTrees.get(ownerRoot);
    const element = retained && retained[record.target];
    if (!(element instanceof global.Element) || !ownerRoot.contains(element)) {
      throw new TypeError("private retained HTML patch target is unavailable");
    }
    const mutation = record.mutation;
    if (mutation.tag === 1 && mutation.name === "" && typeof mutation.value === "string") {
      element.textContent = mutation.value;
      return element;
    }
    if (mutation.tag === 2 && typeof mutation.name === "string" && mutation.name &&
        !/^on/i.test(mutation.name) && typeof mutation.value === "string") {
      element.setAttribute(mutation.name, mutation.value);
      return element;
    }
    throw new TypeError("private retained HTML patch mutation is unsupported");
  }

  function mountInternalTree(ownerRoot, identities) {
    if (!(ownerRoot instanceof global.Element) || !Array.isArray(identities)) {
      throw new TypeError("internal HTML component tree requires an owner and identities");
    }
    const fragment = global.document.createDocumentFragment();
    const mounted = [];
    for (const rawIdentity of identities) {
      const identity = String(rawIdentity || "");
      const Component = global.Object.prototype.hasOwnProperty.call(components, identity)
        ? components[identity]
        : null;
      if (typeof Component !== "function") {
        throw new TypeError("internal HTML component tree received an unknown identity");
      }
      const element = new Component();
      if (!(element instanceof global.Element)) {
        throw new TypeError("internal HTML component constructor did not create an element");
      }
      fragment.appendChild(element);
      mounted.push(element);
    }
    ownerRoot.appendChild(fragment);
    return adoptInternalTree(ownerRoot, mounted);
  }

  global.VfHtmlComponents = components;
  global.Object.defineProperty(global.VfHtmlComponents, "__internal", {
    value: global.Object.freeze({
      catalog: catalog,
      mountTree: mountInternalTree,
      adoptTree: adoptInternalTree,
      applyPatch: applyInternalPatch,
    }),
    enumerable: false,
    writable: false,
    configurable: false,
  });
})(typeof window !== "undefined" ? window : this);
`;
}

function generateCompiler(catalog) {
  const entries = catalog
    .map(([identity, tag]) => `    Entry{"${identity}", "${tag}"},`)
    .join("\n");
  return `// Generated by tools/generate-html-component-catalog.mjs. Do not edit by hand.
#pragma once

#include <array>
#include <string_view>

namespace vf::html_component_catalog {

struct Entry {
    std::string_view identity;
    std::string_view tag;
};

inline constexpr std::array<Entry, ${catalog.length}> kEntries = {{
${entries}
}};

inline constexpr bool Contains(std::string_view identity) noexcept {
    for (const Entry& entry : kEntries) {
        if (entry.identity == identity) return true;
    }
    return false;
}

}  // namespace vf::html_component_catalog
`;
}

const catalog = validateCatalog(JSON.parse(await readFile(catalogPath, "utf8")));
const outputs = [
  [browserPath, generateBrowser(catalog)],
  [compilerPath, generateCompiler(catalog)],
];
if (process.argv.includes("--check")) {
  for (const [outputPath, expected] of outputs) {
    const actual = await readFile(outputPath, "utf8").catch(() => "");
    if (actual !== expected) {
      throw new Error(`${path.relative(repositoryRoot, outputPath)} is not generated from ${path.relative(repositoryRoot, catalogPath)}`);
    }
  }
} else {
  await Promise.all(outputs.map(([outputPath, content]) => writeFile(outputPath, content)));
}
